// Generates public/closure/engine.js from the TypeScript sources, so the page and the tests share ONE engine.
import { stripTypeScriptTypes } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
const rd = f => stripTypeScriptTypes(readFileSync(f, "utf8"), { mode: "strip" })
  .replace(/^import .*$/gm, "").replace(/^export /gm, "");
const body = rd("src/data/real/missionData.ts") + "\n" + rd("src/compute/closure.ts");
const out = `/* GENERATED by scripts/build-closure-page.mjs from src/data/real/missionData.ts + src/compute/closure.ts. Do not edit. */
(function(){
${body}
window.ASTRAIA = { evaluate, spareInstrumentKg, costM, budgetM, LAUNCHERS, INSTRUMENTS, PROPELLANTS, TARGETS, PERSEVERANCE, G0, BUDGET_M, BUS_COST_M, COST_M, SIM_PROV };
})();
`;
writeFileSync("public/closure/engine.js", out);
console.log("engine.js", out.length, "bytes");
